test('dollars and cents are worded with correct agreement', function (string $amount, string $expected) {
    expect(Tafqeet::amount($amount, 'USD'))->toBe($expected);
})->with([
    ['1', 'فقط دولار واحد لا غير'],
    ['2.02', 'فقط دولاران وسنتان لا غير'],
    ['5', 'فقط خمسة دولارات لا غير'],
    ['0.01', 'فقط سنت واحد لا غير'],
    ['0.75', 'فقط خمسة وسبعون سنتًا لا غير'],
    ['1500.75', 'فقط ألف وخمسمائة دولار وخمسة وسبعون سنتًا لا غير'],
    ['12000', 'فقط اثنا عشر ألف دولار لا غير'],
    ['0.999', 'فقط دولار واحد لا غير'], // rounded to cents
]);

test('unknown currencies are refused', function () {
    Tafqeet::amount('10', 'EUR');
